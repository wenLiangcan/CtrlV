import AppKit

@MainActor
final class ClipboardMonitor {
    private var timer: Timer?
    private var changeCount: Int
    private let pasteboard: NSPasteboard
    var onCapture: ((Clip) -> Void)?
    var isPaused = false

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        changeCount = pasteboard.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.45, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.15
    }

    func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard !isPaused, let clip = Self.capture(pasteboard, source: NSWorkspace.shared.frontmostApplication?.localizedName ?? "Clipboard") else { return }
        onCapture?(clip)
    }

    func restore(_ clip: Clip) -> Bool {
        let items = clip.items.map { representations in
            let item = NSPasteboardItem()
            for representation in representations {
                item.setData(representation.data, forType: .init(representation.type))
            }
            return item
        }
        pasteboard.clearContents()
        let success = pasteboard.writeObjects(items)
        changeCount = pasteboard.changeCount
        return success
    }

    static let excludedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb"
    ]

    static func capture(_ pasteboard: NSPasteboard, source: String) -> Clip? {
        let boardTypes = pasteboard.types ?? []
        let itemTypes = pasteboard.pasteboardItems?.flatMap(\.types) ?? []
        let allTypes = Set((boardTypes + itemTypes).map(\.rawValue))
        guard excludedTypes.isDisjoint(with: allTypes), let original = pasteboard.pasteboardItems, !original.isEmpty else { return nil }
        let allowed: [NSPasteboard.PasteboardType] = [.string, .rtf, .html, .png, .tiff, .fileURL, .URL]
        var total = 0
        var items: [[Clip.Representation]] = []
        for item in original {
            var representations: [Clip.Representation] = []
            for type in allowed where item.types.contains(type) {
                // PNG already preserves image content; don't retain a second huge TIFF copy.
                if type == .tiff && item.types.contains(.png) { continue }
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                guard total <= HistoryPolicy.maximumItemBytes else { return nil }
                representations.append(.init(type: type.rawValue, data: data))
            }
            guard !representations.isEmpty else { return nil }
            items.append(representations)
        }
        let first = original[0]
        let text = first.string(forType: .string) ?? first.string(forType: .URL) ?? ""
        let kind: Clip.Kind
        let title: String
        if let file = first.string(forType: .fileURL), let url = URL(string: file) {
            kind = .file
            title = original.count > 1 ? "\(url.lastPathComponent) + \(original.count - 1) more" : url.lastPathComponent
        } else if first.types.contains(.png) || first.types.contains(.tiff) {
            kind = .image
            title = "Copied image"
        } else if !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let clean = text.trimmingCharacters(in: .whitespacesAndNewlines)
            let scheme = URL(string: clean)?.scheme?.lowercased()
            kind = (scheme == "https" || scheme == "http") && !clean.contains(where: \.isWhitespace) ? .link : .text
            title = String(clean.prefix(10_000))
        } else { return nil }
        return Clip(fingerprint: Clip.fingerprint(for: items), kind: kind, title: title, source: source, items: items)
    }
}
