@Test @MainActor func loginStartupSuppressesInitialWindow() {
    let defaultNote = Notification(
        name: NSApplication.didFinishLaunchingNotification,
        object: nil,
        userInfo: [NSApplication.launchIsDefaultUserInfoKey: true]
    )
    let normalEvent = NSAppleEventDescriptor.appleEvent(
        withEventClass: AEEventClass(kCoreEventClass),
        eventID: AEEventID(kAEOpenApplication),
        targetDescriptor: nil,
        returnID: AEReturnID(kAutoGenerateReturnID),
        transactionID: AETransactionID(kAnyTransactionID)
    )
    #expect(AppDelegate.shouldShowOnLaunch(defaultNote, appleEvent: normalEvent))

    let loginEvent = NSAppleEventDescriptor.appleEvent(
        withEventClass: AEEventClass(kCoreEventClass),
        eventID: AEEventID(kAEOpenApplication),
        targetDescriptor: nil,
        returnID: AEReturnID(kAutoGenerateReturnID),
        transactionID: AETransactionID(kAnyTransactionID)
    )
    loginEvent.setParam(
        NSAppleEventDescriptor(enumCode: DescType(keyAELaunchedAsLogInItem)),
        forKeyword: AEKeyword(keyAEPropData)
    )
    #expect(!AppDelegate.shouldShowOnLaunch(defaultNote, appleEvent: loginEvent))

    let nonDefaultNote = Notification(
        name: NSApplication.didFinishLaunchingNotification,
        object: nil,
        userInfo: [NSApplication.launchIsDefaultUserInfoKey: false]
    )
    #expect(!AppDelegate.shouldShowOnLaunch(nonDefaultNote, appleEvent: normalEvent))
}

@Test @MainActor func richTextRoundTripAndSelfCaptureSuppression() {
    let board = NSPasteboard.withUniqueName()
    defer { board.releaseGlobally() }
    let monitor = ClipboardMonitor(pasteboard: board)
    var captures: [Clip] = []
    monitor.onCapture = { captures.append($0) }
    board.clearContents()
    board.setString("Hello world", forType: .string)
    let rich = Data(#"{\rtf1 Hello \b world}"#.utf8)
    board.setData(rich, forType: .rtf)
    monitor.poll()
    #expect(captures.count == 1)
    guard let captured = captures.first else { return }
    #expect(monitor.restore(captured))
    #expect(board.data(forType: .rtf) == rich)
    monitor.poll()
    #expect(captures.count == 1)
}

@Test @MainActor func pauseSkipsCopiesWithoutBackfill() {
    let board = NSPasteboard.withUniqueName()
    defer { board.releaseGlobally() }
    let monitor = ClipboardMonitor(pasteboard: board)
    var count = 0
    monitor.onCapture = { _ in count += 1 }
    monitor.isPaused = true
    board.setString("ignored", forType: .string)
    monitor.poll()
    monitor.isPaused = false
    monitor.poll()
    #expect(count == 0)
    board.clearContents()
    board.setString("captured", forType: .string)
    monitor.poll()
    #expect(count == 1)
}

@Test func persistenceRoundTrip() async throws {
    let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
    defer { try? FileManager.default.removeItem(at: directory) }
    let persistence = HistoryPersistence(url: directory.appendingPathComponent("history.json"))
    let original = [clip("saved", pinned: true), clip("second")]
    let saved = await withCheckedContinuation { continuation in
        persistence.save(original) { continuation.resume(returning: $0) }
    }
    #expect(saved)
    let loaded = await persistence.load()
    #expect(loaded == original)
    let attributes = try FileManager.default.attributesOfItem(atPath: persistence.url.path)
    #expect((attributes[.posixPermissions] as? NSNumber)?.intValue == 0o600)
}

@Test @MainActor func multipleFileURLsRoundTrip() throws {
    let board = NSPasteboard.withUniqueName()
    defer { board.releaseGlobally() }
    let urls = [URL(fileURLWithPath: "/tmp/First document.txt"), URL(fileURLWithPath: "/tmp/Second.png")]
    board.writeObjects(urls as [NSURL])
    let captured = try #require(ClipboardMonitor.capture(board, source: "Finder"))
    #expect(captured.kind == .file)
    #expect(captured.items.count == 2)
    let monitor = ClipboardMonitor(pasteboard: board)
    #expect(monitor.restore(captured))
    #expect(board.pasteboardItems?.compactMap { $0.string(forType: .fileURL) } == urls.map(\.absoluteString))
}

