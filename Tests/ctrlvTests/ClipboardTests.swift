private func clip(_ text: String, pinned: Bool = false) -> Clip {
    let items: [[Clip.Representation]] = [[.init(type: NSPasteboard.PasteboardType.string.rawValue, data: Data(text.utf8))]]
    var clip = Clip(fingerprint: Clip.fingerprint(for: items), kind: .text, title: text, source: "Tests", items: items)
    clip.isPinned = pinned
    return clip
}

@Test func deduplicationPreservesIdentityAndPins() {
    let original = clip("hello", pinned: true)
    let history = HistoryPolicy.inserting(clip("hello"), into: [clip("world"), original])
    #expect(history.count == 2)
    #expect(history.first?.id == original.id)
    #expect(history.first?.isPinned == true)
}

@Test func evictionPreservesPinnedItems() {
    let pinned = clip("keep", pinned: true)
    let history = (0..<230).reduce([pinned]) { HistoryPolicy.inserting(clip("item \($1)"), into: $0) }
    #expect(history.count == 200)
    #expect(history.contains { $0.id == pinned.id })
    #expect(history.first?.title == "item 229")
    #expect(!history.contains { $0.title == "item 0" })
}

@Test func memoryBudgetEvictsOldestUnpinned() {
    let data = Data(repeating: 42, count: 3 * 1_024 * 1_024)
    let history = (0..<15).reduce([Clip]()) { history, index in
        let entry = Clip(fingerprint: String(index), kind: .image, title: "Image", source: "Tests",
                         items: [[.init(type: "public.png", data: data)]])
        return HistoryPolicy.inserting(entry, into: history)
    }
    #expect(history.reduce(0) { $0 + $1.byteCount } <= HistoryPolicy.maximumBytes)
    #expect(history.first?.fingerprint == "14")
}

