@Test @MainActor func scrollBarHidesOnNoMovementAndShowsOnScroll() async throws {
    let scrollView = NSScrollView(frame: NSRect(x: 0, y: 0, width: 300, height: 200))
    scrollView.hasVerticalScroller = true
    scrollView.documentView = NSView(frame: NSRect(x: 0, y: 0, width: 300, height: 1000))
    scrollView.tile()

    let observer = ScrollBarObserverView()
    observer.hideDelay = .milliseconds(50)
    observer.attach(to: scrollView)

    let scroller = try #require(scrollView.verticalScroller)
    #expect(scrollView.scrollerStyle == .overlay)
    #expect(!observer.isScrolling)
    #expect(scroller.alphaValue == 0)
    #expect(scroller.isHidden)

    // Re-tiling or attempting to switch to legacy scrollers without movement keeps it hidden.
    scrollView.scrollerStyle = .legacy
    scrollView.tile()
    scrollView.reflectScrolledClipView(scrollView.contentView)
    #expect(scrollView.scrollerStyle == .overlay)
    #expect(scroller.alphaValue == 0)
    #expect(scroller.isHidden)

    // Scroll movement shows the scrollbar.
    scrollView.contentView.scroll(to: NSPoint(x: 0, y: 120))
    scrollView.reflectScrolledClipView(scrollView.contentView)
    #expect(observer.isScrolling)
    #expect(scroller.alphaValue == 1)
    #expect(!scroller.isHidden)

    // After movement stops, the scrollbar automatically hides again.
    try await Task.sleep(for: .milliseconds(100))
    #expect(!observer.isScrolling)
    #expect(scroller.alphaValue == 0)
    #expect(scroller.isHidden)
}

